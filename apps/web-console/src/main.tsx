  function updateOnboardingFromDomains(items: DomainRecord[]): void {
    if (items.length === 0) {
      setShowOnboardingWizard(true);
      setOnboardingStep(1);
      setLaunchAssistantStep(1);
      setView("launchAssistant");
      return;
    }

    const hasSSL = items.some(
      (item) =>
        item.tls?.status === "issued" ||
        item.tls?.status === "expiring" ||
        item.tls?.status === "pending",
    );

    if (!hasSSL) {
      setShowOnboardingWizard(true);
      setOnboardingStep(2);
      setLaunchAssistantStep(2);
      if (view === "onboarding" || view === "launchAssistant") {
        setView("launchAssistant");
        setStatus("Next step: issue SSL for your domain.");
      }
      return;
    }

    setShowOnboardingWizard(false);
    setOnboardingStep(3);
    setLaunchAssistantStep(3);
    if (view === "onboarding" || view === "launchAssistant") {
      setView("home");
      setStatus("Onboarding complete. PanelX is ready.");
    }
  }

