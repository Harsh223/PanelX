  async function createDomain(): Promise<void> {
    const hostname = domainForm.hostname.trim();

    if (!hostname) {
      setStatus("Hostname is required");
      return;
    }
    if (!isLikelyDomainOrIP(hostname) || hostname.includes(" ")) {
      setStatus(
        "Use a valid hostname like example.com or blog.example.com (no spaces).",
      );
      return;
    }

    setStatus("Creating domain...");
    try {
      const created = await apiFetch<DomainRecord>("/v1/domains/create", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          hostname: domainForm.hostname.trim(),
          documentRoot: domainForm.documentRoot.trim(),
          ownerLabel: domainForm.ownerLabel.trim(),
          notes: domainForm.notes.trim(),
          enableNginx: domainForm.enableNginx,
        }),
      });

      setSelectedDomain(created);
      setRedirectForm({
        mode: created.redirects?.mode ?? "off",
        canonicalHost: created.redirects?.canonicalHost ?? "none",
        canonicalTarget: created.redirects?.canonicalTarget ?? "",
        customTargetUrl: created.redirects?.customTargetUrl ?? "",
        preservePath: created.redirects?.preservePath ?? true,
        preserveQuery: created.redirects?.preserveQuery ?? true,
        temporary: created.redirects?.temporary ?? false,
      });
      setDomainForm({
        hostname: "",
        documentRoot: "",
        ownerLabel: "",
        notes: "",
        enableNginx: true,
      });
      const items = await loadDomains(false, true);
      updateOnboardingFromDomains(items);
      setStatus(`Domain ${created.hostname} created`);
      pushToast(`Domain ${created.hostname} added`, "success");
    } catch (error) {
      const msg = `Create domain failed: ${errorMessage(error)}`;
      setStatus(msg);
      pushToast(msg, "error", 4200);
    }
  }

