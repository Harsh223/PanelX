  async function listFiles(nextPath?: string): Promise<void> {
    if (!fileDomain.trim()) {
      setStatus("File manager requires domain/IP");
      return;
    }

    const effectivePath =
      typeof nextPath === "string" ? nextPath : filePath.trim();

    setStatus("Loading file list...");
    try {
      const params = new URLSearchParams({
        domain: fileDomain.trim(),
        path: effectivePath,
      });
      const data = await apiFetch<{ entries: FileEntry[] }>(
        `/v1/files/list?${params.toString()}`,
        {
          method: "GET",
          credentials: "include",
        },
      );
      const loadedEntries = data.entries ?? [];
      const sortedEntries = [...loadedEntries].sort((a, b) => {
        if (a.isDir !== b.isDir) return a.isDir ? -1 : 1;
        return a.name.localeCompare(b.name, undefined, {
          sensitivity: "base",
          numeric: true,
        });
      });

      setEntries(sortedEntries);
      setFilePath(effectivePath);

      if (sortedEntries.length === 0) {
        setStatus(
          "This folder is empty. You can browse another path or create/upload files via your app deployment flow.",
        );
      } else {
        setStatus(
          `Loaded ${sortedEntries.length} items (folders first, then files). Select a file to preview or edit.`,
        );
      }
    } catch (error) {
      setStatus(`List files failed: ${errorMessage(error)}`);
    }
  }

