function buildOnboardingSummary(
  domains: DomainRecord[],
  installations: Installation[],
): { summary: string; nextStep: string; ready: boolean } {
  const hasDomain = domains.length > 0;
  const hasSSL = domains.some(
    (d) => d.tls?.status === "issued" || d.tls?.status === "expiring",
  );
  const hasWordPress = installations.length > 0;

  if (!hasDomain) {
    return {
      summary: "No managed domain yet. Start by adding your first domain.",
      nextStep: "Add your first domain",
      ready: false,
    };
  }

  if (!hasSSL) {
    return {
      summary:
        "Domain added, but HTTPS is not ready yet. Issue an SSL certificate next.",
      nextStep: "Issue SSL for your domain",
      ready: false,
    };
  }

  if (!hasWordPress) {
    return {
      summary:
        "Domain and SSL look good. Install WordPress to complete launch setup.",
      nextStep: "Run one-click WordPress install",
      ready: false,
    };
  }

  return {
    summary:
      "Domain, SSL, and WordPress are all configured. Your site environment is ready.",
    nextStep: "Review files or open wp-admin",
    ready: true,
  };
}

function buildLaunchAssistantProgress(
  selectedDomain: DomainRecord | null,
  installations: Installation[],
): {
  domainReady: boolean;
  sslReady: boolean;
  wordpressReady: boolean;
  completedSteps: number;
  totalSteps: number;
  nextStep: LaunchAssistantStep;
  ctaLabel: string;
} {
  const domainReady = !!selectedDomain;
  const sslReady =
    !!selectedDomain &&
    (selectedDomain.tls?.status === "issued" ||
      selectedDomain.tls?.status === "expiring" ||
      selectedDomain.tls?.status === "pending");

  const wordpressReady =
    !!selectedDomain &&
    installations.some(
      (item) =>
        item.domain.trim().toLowerCase() ===
        selectedDomain.hostname.trim().toLowerCase(),
    );

  const completedSteps =
    (domainReady ? 1 : 0) + (sslReady ? 1 : 0) + (wordpressReady ? 1 : 0);

  if (!domainReady) {
    return {
      domainReady,
      sslReady,
      wordpressReady,
      completedSteps,
      totalSteps: 3,
      nextStep: 1,
      ctaLabel: "Add your first domain",
    };
  }

  if (!sslReady) {
    return {
      domainReady,
      sslReady,
      wordpressReady,
      completedSteps,
      totalSteps: 3,
      nextStep: 2,
      ctaLabel: "Issue SSL certificate",
    };
  }

  if (!wordpressReady) {
    return {
      domainReady,
      sslReady,
      wordpressReady,
      completedSteps,
      totalSteps: 3,
      nextStep: 3,
      ctaLabel: "Install WordPress",
    };
  }

  return {
    domainReady,
    sslReady,
    wordpressReady,
    completedSteps,
    totalSteps: 3,
    nextStep: 4,
    ctaLabel: "Open your site",
  };
}



